const PACKS: Record<BotLocale, typeof zh> = { 'zh-CN': zh, 'en-US': en, 'es-ES': es };

export const pack = (locale: BotLocale) => PACKS[locale] ?? zh;

/** 简单插值：{{name}} */
export function fill(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{\{(\w+)\}\}/g, (_, k: string) => String(vars[k] ?? ''));
}

/** "title.leverageManiac" → 毒舌称号 */
export const titleName = (locale: BotLocale, key: string) => pack(locale).title[key.replace(/^title\./, '')] ?? key;
export const badgeName = (locale: BotLocale, key: string) => pack(locale).badge[key] ?? key;
